def load(out, base, set_name, label):
    path = result_path(out, base, set_name, label)
    return np.load(path)['curves'] if os.path.exists(path) else None


def table(out, base, target, cols, sets, gen, paper_rows=None):
    """target: algorithm label, or {set: label, '*': default label}."""
    width = max(14, *(len(c) + 2 for c in cols))
    head = f'{"set":8s}' + ''.join(f'{c:>{width}s}' for c in cols)
    lines = [head, '-' * len(head)]
    for s in sets:
        tgt = target.get(s, target.get('*')) if isinstance(target, dict) else target
        a = load(out, base, s, tgt)
        ours = []
        for c in cols:
            name, g = (c.split('@')[0], int(c.split('@')[1])) if '@' in c else (c, gen)
            b = load(out, base, s, name)
            ours.append(fmt_wtl(*wtl(a, b, g)) if a is not None and b is not None else '-')
        lines.append(f'{s:8s}' + ''.join(f'{x:>{width}s}' for x in ours))
        if paper_rows and s in paper_rows:
            ref = [fmt_wtl(*map(int, x.split('/'))) for x in paper_rows[s].split()]
            lines.append(f'{"  paper":8s}' + ''.join(f'{x:>{width}s}' for x in ref))
    return '\n'.join(lines)


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--table', choices=sorted(PAPER))
    p.add_argument('--target', default=None)
    p.add_argument('--vs', nargs='+')
    p.add_argument('--sets', nargs='+')
    p.add_argument('--gen', type=int, default=250)
    p.add_argument('--base', default='DE')
    p.add_argument('--out', default='l2t_runs')
    args = p.parse_args(argv)
    if args.table:
        t = PAPER[args.table]
        sets = args.sets or list(t['rows'])
        when = f'at generation {t["gen"]}' if t['gen'] else '(column@generation)'
        print(f'Table {args.table}: L2T ({t["base"]}) W/T/L {when}; paper values on the "paper" lines\n')
        print(table(args.out, t['base'], args.target or t['target'], t['cols'], sets, t['gen'], t['rows']))
    else:
        print(table(args.out, args.base, args.target or 'L2T', args.vs, args.sets, args.gen))


if __name__ == '__main__':
    main()
